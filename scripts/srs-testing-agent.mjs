import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const args = new Set(process.argv.slice(2));
const shouldGenerate = args.has("--generate");
const configPath = path.join(root, "docs/srs-testing/agent.config.json");

async function main() {
  const config = await readJson(configPath);
  const outputDir = path.join(root, config.outputDir);
  await fs.mkdir(outputDir, { recursive: true });

  const env = await loadEnv(path.join(root, ".env"));
  const prompt = await readText(path.join(root, config.promptFile));
  const files = await collectSourceFiles(config);
  const bundle = await buildContextBundle(files, config);
  const runPrompt = buildRunPrompt(config, prompt, bundle);

  const contextPath = path.join(outputDir, "context-bundle.md");
  const promptPath = path.join(outputDir, "run-prompt.md");
  await fs.writeFile(contextPath, bundle, "utf8");
  await fs.writeFile(promptPath, runPrompt, "utf8");

  console.log(`Prepared ${files.length} source files.`);
  console.log(`Context: ${relative(contextPath)}`);
  console.log(`Prompt: ${relative(promptPath)}`);

  if (!shouldGenerate) {
    console.log("Done. Run with --generate or npm run srs:agent:generate to call the configured AI provider.");
    return;
  }

  const provider = getEnv(env, "AI_PROVIDER", "openai").toLowerCase();
  const output = provider === "gemini" || provider === "google"
    ? await callGemini(env, runPrompt)
    : await callOpenAI(env, runPrompt);

  const outputPath = path.join(outputDir, "agent-output.md");
  await fs.writeFile(outputPath, output, "utf8");
  console.log(`AI draft: ${relative(outputPath)}`);
}

async function readJson(filePath) {
  return JSON.parse(await readText(filePath));
}

async function readText(filePath) {
  return fs.readFile(filePath, "utf8");
}

async function loadEnv(filePath) {
  const values = { ...process.env };
  try {
    const content = await readText(filePath);
    for (const rawLine of content.split(/\r?\n/)) {
      const line = rawLine.trim();
      if (!line || line.startsWith("#") || !line.includes("=")) continue;
      const [key, ...rest] = line.split("=");
      const value = rest.join("=").trim().replace(/^["']|["']$/g, "");
      if (key.trim() && values[key.trim()] === undefined) {
        values[key.trim()] = value;
      }
    }
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  return values;
}

async function collectSourceFiles(config) {
  const collected = [];
  for (const source of config.sources) {
    const absolute = path.join(root, source.path);
    const stat = await safeStat(absolute);
    if (!stat) continue;

    if (stat.isFile()) {
      collected.push(absolute);
      continue;
    }

    if (stat.isDirectory()) {
      const extensions = new Set(source.extensions ?? []);
      const files = await walk(absolute, config.excludeDirectories ?? []);
      for (const file of files) {
        if (extensions.size === 0 || extensions.has(path.extname(file))) {
          collected.push(file);
        }
      }
    }
  }

  return [...new Set(collected)].sort((a, b) => relative(a).localeCompare(relative(b)));
}

async function walk(directory, excludeDirectories) {
  const output = [];
  const entries = await fs.readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (isExcluded(absolute, excludeDirectories)) continue;
      output.push(...await walk(absolute, excludeDirectories));
      continue;
    }
    if (entry.isFile()) output.push(absolute);
  }
  return output;
}

function isExcluded(absolute, excludeDirectories) {
  const normalized = slash(relative(absolute));
  return excludeDirectories.some((item) => normalized === item || normalized.startsWith(`${item}/`));
}

async function safeStat(filePath) {
  try {
    return await fs.stat(filePath);
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

async function buildContextBundle(files, config) {
  const maxFileCharacters = config.maxFileCharacters ?? 30000;
  const maxTotalCharacters = config.maxTotalCharacters ?? 180000;
  const sections = [
    "# StudyMate Source Context Bundle",
    "",
    "This file is generated by scripts/srs-testing-agent.mjs.",
    "Do not paste secrets into this bundle.",
    ""
  ];

  let total = sections.join("\n").length;

  for (const file of files) {
    let content = await readText(file);
    if (content.length > maxFileCharacters) {
      content = `${content.slice(0, maxFileCharacters)}\n\n[TRUNCATED: file exceeded maxFileCharacters]`;
    }

    const block = [
      `## File: ${slash(relative(file))}`,
      "",
      fenceFor(file),
      content,
      "```",
      ""
    ].join("\n");

    if (total + block.length > maxTotalCharacters) {
      sections.push(`[STOPPED: bundle exceeded maxTotalCharacters=${maxTotalCharacters}]`);
      break;
    }

    sections.push(block);
    total += block.length;
  }

  return sections.join("\n");
}

function buildRunPrompt(config, prompt, bundle) {
  return [
    "# Run Prompt - StudyMate SRS Testing Agent",
    "",
    prompt.trim(),
    "",
    "## Target output files",
    "",
    ...config.targetDocs.map((file) => `- ${file}`),
    "",
    "## Additional instruction",
    "",
    "Use the source context below as evidence. Write concise, test-oriented Vietnamese documentation. Keep PlantUML and Mermaid diagrams runnable.",
    "",
    bundle
  ].join("\n");
}

function fenceFor(file) {
  const extension = path.extname(file).toLowerCase();
  const language = {
    ".php": "php",
    ".jsx": "jsx",
    ".js": "js",
    ".sql": "sql",
    ".json": "json",
    ".md": "markdown"
  }[extension] ?? "";
  return `\`\`\`${language}`;
}

async function callOpenAI(env, prompt) {
  const apiKey = getEnvAny(env, ["AI_API_KEY", "OPENAI_API_KEY"]);
  if (!apiKey) {
    throw new Error("Missing AI_API_KEY or OPENAI_API_KEY. Add it to .env or run without --generate.");
  }

  const apiUrl = getEnv(env, "AI_API_URL", "https://api.openai.com/v1/chat/completions");
  const model = getEnv(env, "AI_MODEL", "gpt-4o-mini");
  const timeout = Number(getEnv(env, "AI_TIMEOUT", "60")) * 1000;

  const response = await fetchWithTimeout(apiUrl, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Authorization": `Bearer ${apiKey}`
    },
    body: JSON.stringify({
      model,
      temperature: 0.2,
      messages: [
        {
          role: "system",
          content: "You are a software QA documentation agent. Return Markdown only."
        },
        {
          role: "user",
          content: prompt
        }
      ]
    })
  }, timeout);

  const data = await response.json();
  if (!response.ok) {
    throw new Error(data?.error?.message ?? `OpenAI API returned HTTP ${response.status}`);
  }

  return data?.choices?.[0]?.message?.content ?? "";
}

async function callGemini(env, prompt) {
  const apiKey = getEnvAny(env, ["GEMINI_API_KEY", "GOOGLE_API_KEY"]);
  if (!apiKey) {
    throw new Error("Missing GEMINI_API_KEY or GOOGLE_API_KEY. Add it to .env or run without --generate.");
  }

  const model = getEnv(env, "GEMINI_MODEL", "gemini-3.6-flash").replace(/^models\//, "");
  const baseUrl = getEnv(env, "GEMINI_API_URL", "https://generativelanguage.googleapis.com/v1beta/models").replace(/\/$/, "");
  const timeout = Number(getEnv(env, "AI_TIMEOUT", "60")) * 1000;
  const url = `${baseUrl}/${encodeURIComponent(model)}:generateContent`;

  const response = await fetchWithTimeout(url, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "x-goog-api-key": apiKey
    },
    body: JSON.stringify({
      contents: [
        {
          role: "user",
          parts: [{ text: prompt }]
        }
      ],
      generationConfig: {
        temperature: 0.2
      }
    })
  }, timeout);

  const data = await response.json();
  if (!response.ok) {
    throw new Error(data?.error?.message ?? `Gemini API returned HTTP ${response.status}`);
  }

  return data?.candidates?.[0]?.content?.parts?.[0]?.text ?? "";
}

async function fetchWithTimeout(url, options, timeoutMs) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), timeoutMs);
  try {
    return await fetch(url, { ...options, signal: controller.signal });
  } finally {
    clearTimeout(timeout);
  }
}

function getEnv(env, key, fallback = "") {
  return env[key] || fallback;
}

function getEnvAny(env, keys) {
  for (const key of keys) {
    if (env[key]) return env[key];
  }
  return "";
}

function relative(filePath) {
  return path.relative(root, filePath);
}

function slash(value) {
  return value.split(path.sep).join("/");
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
